def analyze_self_esteem(answers: list) -> dict:
    """
    Анализ самооценки на основе ответов на 30 вопросов
    
    Args:
        answers: список из 30 ответов пользователя
    
    Returns:
        dict с результатами анализа
    """
    # Подсчет баллов по блокам
    scores = {
        'self_worth': 0,      # Самооценка (вопросы 1-6)
        'fears': 0,           # Страхи (вопросы 7-12)
        'anger': 0,           # Гнев и обиды (вопросы 13-18)
        'purpose': 0,         # Предназначение (вопросы 19-24)
        'relationships': 0    # Отношения (вопросы 25-30)
    }
    
    # Анализ ответов (упрощенная версия, можно дополнить AI анализом)
    negative_keywords = ['нет', 'не', 'никогда', 'редко', 'плохо', 'низко', 'боюсь', 'страшно', 'тревожно']
    positive_keywords = ['да', 'хорошо', 'высоко', 'часто', 'легко', 'уверен', 'верю', 'люблю']
    
    # Простой подсчет (можно заменить на AI анализ)
    for i, answer in enumerate(answers):
        answer_lower = answer.lower()
        score = 5  # нейтральный балл
        
        # Подсчет позитивных и негативных слов
        positive_count = sum(1 for kw in positive_keywords if kw in answer_lower)
        negative_count = sum(1 for kw in negative_keywords if kw in answer_lower)
        
        score += positive_count * 2
        score -= negative_count * 2
        score = max(0, min(10, score))  # ограничиваем 0-10
        
        # Распределение по блокам
        if i < 6:
            scores['self_worth'] += score
        elif i < 12:
            scores['fears'] += score
        elif i < 18:
            scores['anger'] += score
        elif i < 24:
            scores['purpose'] += score
        else:
            scores['relationships'] += score
    
    # Нормализация (средний балл по каждому блоку)
    for key in scores:
        scores[key] = round(scores[key] / 6, 1)
    
    return scores

